import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const base = process.env.APP_URL || 'http://127.0.0.1:5173';
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
const evidence = [];
const name = `accept_${Date.now().toString(36)}`;
try {
  await page.goto(base);
  await page.waitForFunction(() => window.stepfun && document.querySelector('#kb').options.length);
  page.once('dialog', d => d.accept(name));
  await page.click('#new');
  await page.waitForFunction(name => document.querySelector('#kb').value === `sf_${name}`, name);
  await page.click('summary');
  await page.selectOption('#device', 'wasm');
  await page.fill('#paste', '星屿验收标记：蓝鲸喜欢在珊瑚礁旁收集海洋温度数据。离线采集设备每隔三十分钟采样，并将记录存储在本地数据库。');
  await page.click('#import');
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('可以检索'), null, { timeout: 120000 });
  assert.match(await page.textContent('#backend'), /WASM/);
  evidence.push('通过界面导入文本、浏览器 INT8 WASM 推理、写入和索引刷新');
  await page.fill('#query', '蓝鲸如何采集温度数据'); await page.click('#search button');
  await page.waitForFunction(() => document.querySelector('#status').textContent === '检索完成');
  assert.match(await page.textContent('#results'), /蓝鲸/);
  evidence.push('通过界面自然语言查询并显示 seekdb 混合检索原文');
  await page.screenshot({ path: 'reports/application.png', fullPage: true });
  await page.fill('#paste', '增量验收：海豚观测站位于南海的星沙岛，设备每周星期三进行维护。'); await page.click('#import');
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('可以检索'), null, { timeout: 120000 });
  await page.fill('#query', '海豚观测站什么时候维护'); await page.click('#search button');
  await page.waitForFunction(() => document.querySelector('#status').textContent === '检索完成');
  assert.match(await page.textContent('#results'), /星期三/);
  evidence.push('同一知识库增量写入后可以立即混合检索新增原文');
  page.once('dialog', d => d.accept(`${name}_empty`)); await page.click('#new');
  await page.waitForFunction(name => document.querySelector('#kb').value === `sf_${name}_empty`, name);
  assert.equal(await page.textContent('#results'), '');
  await page.fill('#query', '蓝鲸温度'); await page.click('#search button');
  await page.waitForFunction(() => document.querySelector('#status').textContent === '检索完成');
  assert.equal(await page.locator('#results article').count(), 0);
  evidence.push('切换空知识库时清空结果，查询不返回其他集合数据');
  await page.selectOption('#kb', `sf_${name}`); await page.reload();
  await page.waitForFunction(() => document.querySelector('#kb').options.length > 0);
  assert((await page.locator('#kb option').allTextContents()).some(t => t.includes(name) && t.includes('2 个片段')));
  evidence.push('页面刷新后从 seekdb 恢复集合列表及片段数量');
  const invalid = await page.evaluate(async () => {
    const r = await fetch('/api/kbs/sf_bad/search', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({text:'test',embedding:[1,2,3]}) });
    return r.status;
  }); assert.equal(invalid, 400); evidence.push('拒绝错误维度向量');
  await page.click('summary'); await page.selectOption('#device', 'auto');
  await page.selectOption('#kb', `sf_${name}`);
  await page.fill('#query', '海豚观测站什么时候维护'); await page.click('#search button');
  await page.waitForFunction(() => document.querySelector('#status').textContent === '检索完成');
  assert.match(await page.textContent('#results'), /星期三/);
  const backend = await page.textContent('#backend');
  if (backend.includes('WASM')) assert.match(backend, /已自动降级/);
  evidence.push(`自动后端选择下完整检索及界面提示：${backend}`);
  await page.screenshot({ path: 'reports/automatic-backend.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 }); await page.screenshot({ path: 'reports/mobile.png', fullPage: true });
  await writeFile('reports/acceptance.json', JSON.stringify({ at: new Date().toISOString(), browser: browser.version(), evidence }, null, 2));
  console.log(evidence.join('\n'));
} finally { await browser.close(); }
